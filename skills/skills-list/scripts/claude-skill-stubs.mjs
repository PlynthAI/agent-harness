#!/usr/bin/env node
// Claude skill stubs.
//
// A repository keeps its own skills in .codex/skills. Claude Code discovers
// repository skills only in .claude/skills, and committed links break in Windows
// clones, CI and worktrees. So each source skill gets a small generated stub in
// .claude/skills/<name>/SKILL.md: the source frontmatter copied verbatim, so
// Claude sees the same name and trigger, and a body that points back at the
// source. The stubs are committed; --check keeps them fresh.
//
// A .claude/skills folder whose SKILL.md lacks the marker is the repository's
// own Claude skill. It is never written or removed.
import {
  existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, realpathSync, rmdirSync, unlinkSync, writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readFrontmatter } from './list-skills.mjs';

export const MARKER = '<!-- generated by claude-skill-stubs; do not edit -->';
const REGENERATE = 'node <shared-skills>/skills-list/scripts/claude-skill-stubs.mjs --write';
// The same block readFrontmatter parses, taken whole so it can be copied as is.
const FRONTMATTER_BLOCK = /^﻿?---\r?\n[\s\S]*?\r?\n---(?:\r?\n|$)/;

const USAGE = [
  'usage: claude-skill-stubs.mjs [--write | --check] [--root DIR]',
  '',
  '  (no flag)   report what --write would do; exit 0',
  '  --write     create or update stubs, remove orphaned stubs',
  '  --check     exit 1 on any stale, missing or orphaned stub, collision or unstubbable source',
  '  --root DIR  repository root (default: current directory)',
  '',
].join('\n');

export function parseArgs(argv) {
  const options = { mode: 'report', root: process.cwd(), help: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--write' || arg === '--check') {
      const mode = arg.slice(2);
      if (options.mode !== 'report' && options.mode !== mode) throw new Error('--write and --check are exclusive');
      options.mode = mode;
    } else if (arg === '--root') {
      const value = argv[++i];
      if (value === undefined || value === '') throw new Error('--root needs a value');
      options.root = value;
    } else if (arg === '--help' || arg === '-h') options.help = true;
    else throw new Error(`unknown argument: ${arg}`);
  }
  options.root = path.resolve(options.root);
  return options;
}

// Real folders only: a dot folder is not a skill, and a file is not a folder.
function skillFolders(dir) {
  try {
    return readdirSync(dir, { withFileTypes: true })
      .filter((entry) => (entry.isDirectory() || entry.isSymbolicLink()) && !entry.name.startsWith('.'))
      .map((entry) => entry.name)
      .sort();
  } catch {
    return [];
  }
}

function isLink(p) {
  return lstatSync(p, { throwIfNoEntry: false })?.isSymbolicLink() ?? false;
}

export function stubContent(name, sourceText) {
  const block = sourceText.match(FRONTMATTER_BLOCK)?.[0];
  if (!block) return null;
  const eol = sourceText.includes('\r\n') ? '\r\n' : '\n';
  const head = /\r?\n$/.test(block) ? block : block + eol;
  const body = [
    '',
    MARKER,
    '',
    `Read and follow \`.codex/skills/${name}/SKILL.md\` from the repository root. Its references and scripts resolve from that folder, not from this one.`,
    '',
    `Regenerate with \`${REGENERATE}\`, where \`<shared-skills>\` is the installed harness skills folder.`,
    '',
  ];
  return head + body.join(eol);
}

// One entry per name across both roots, each with the state it is in and the
// content a write would leave there.
export function plan(root) {
  const sourceRoot = path.join(root, '.codex', 'skills');
  const targetRoot = path.join(root, '.claude', 'skills');
  for (const p of [path.join(root, '.claude'), targetRoot]) {
    if (isLink(p)) throw new Error(`${p} is a link; stubs are written only into a real folder`);
  }
  if (existsSync(sourceRoot) && existsSync(targetRoot) && realpathSync(sourceRoot) === realpathSync(targetRoot)) {
    throw new Error(`${targetRoot} resolves to ${sourceRoot}; stubs are written only into a real folder`);
  }

  const entries = new Map();
  for (const name of skillFolders(sourceRoot)) {
    const file = path.join(sourceRoot, name, 'SKILL.md');
    if (!existsSync(file)) continue;
    entries.set(name, { name, source: file });
  }
  for (const name of skillFolders(targetRoot)) {
    const dir = path.join(targetRoot, name);
    const file = path.join(dir, 'SKILL.md');
    const linked = isLink(dir);
    // An empty real folder holds no skill; a write fills it like a missing stub.
    if (!linked && !existsSync(file)) continue;
    const entry = entries.get(name) ?? { name };
    entry.targetDir = dir;
    entry.target = file;
    // A linked folder, or a SKILL.md without the marker, belongs to the repository.
    entry.generated = !linked && readFileSync(file, 'utf8').includes(MARKER);
    entries.set(name, entry);
  }

  const items = [];
  for (const name of [...entries.keys()].sort()) {
    const entry = entries.get(name);
    if (!entry.source) {
      items.push(entry.generated
        ? { ...entry, state: 'orphan', note: 'source .codex/skills/' + name + ' no longer exists' }
        : { ...entry, state: 'own', note: 'own skill, left alone' });
      continue;
    }
    if (entry.target && !entry.generated) {
      items.push({ ...entry, state: 'collision', note: 'a hand-written .claude/skills skill has the same name as a .codex/skills source' });
      continue;
    }
    const front = readFrontmatter(entry.source);
    if (!front.frontmatter) { items.push({ ...entry, state: 'invalid', note: 'no frontmatter' }); continue; }
    if (!front.name) { items.push({ ...entry, state: 'invalid', note: 'no name in frontmatter' }); continue; }
    const text = stubContent(name, readFileSync(entry.source, 'utf8'));
    if (text === null) { items.push({ ...entry, state: 'invalid', note: 'frontmatter block is not closed on its own line' }); continue; }
    const content = Buffer.from(text, 'utf8');
    const target = entry.target ?? path.join(targetRoot, name, 'SKILL.md');
    const current = existsSync(target) ? readFileSync(target) : null;
    const state = current === null ? 'missing' : current.equals(content) ? 'ok' : 'stale';
    items.push({ ...entry, target, targetDir: path.dirname(target), content, state });
  }
  return items;
}

const FAILING = new Set(['missing', 'stale', 'orphan', 'collision', 'invalid']);
const ACTION = { missing: 'create', stale: 'update', orphan: 'remove' };

function line(label, name, note) {
  return `  ${label.padEnd(9)} ${name}${note ? `: ${note}` : ''}\n`;
}

function applyItem(item) {
  if (item.state === 'missing' || item.state === 'stale') {
    mkdirSync(item.targetDir, { recursive: true });
    writeFileSync(item.target, item.content);
    return null;
  }
  if (item.state === 'orphan') {
    unlinkSync(item.target);
    // Only the stub is ours. Anything else left in its folder stays.
    try {
      rmdirSync(item.targetDir);
    } catch {
      return 'stub removed; other files remain in the folder';
    }
  }
  return null;
}

export function main(argv, out = process.stdout) {
  const options = parseArgs(argv);
  if (options.help) {
    out.write(USAGE);
    return 0;
  }
  if (!existsSync(options.root)) throw new Error(`root not found: ${options.root}`);
  const items = plan(options.root);
  const failures = items.filter((item) => FAILING.has(item.state));

  if (options.mode === 'check') {
    out.write(`claude-skill-stubs check: ${options.root}\n`);
    for (const item of items) {
      if (FAILING.has(item.state)) out.write(line(item.state, item.name, item.note));
      else if (item.state === 'own') out.write(line('own', item.name, item.note));
    }
    const ok = items.filter((item) => item.state === 'ok').length;
    out.write(failures.length === 0
      ? `${ok} stub(s) up to date.\n`
      : `${failures.length} problem(s). Run ${REGENERATE} from the repository root.\n`);
    return failures.length === 0 ? 0 : 1;
  }

  out.write(`claude-skill-stubs ${options.mode === 'write' ? 'write' : 'report (no files changed)'}: ${options.root}\n`);
  let changed = 0;
  let unresolved = 0;
  for (const item of items) {
    const action = ACTION[item.state];
    if (action) {
      const note = options.mode === 'write' ? applyItem(item) : null;
      out.write(line(action, item.name, note ?? item.note));
      changed += 1;
    } else if (item.state === 'ok') {
      out.write(line('ok', item.name));
    } else {
      // own, collision or invalid: reported, never written.
      out.write(line(item.state, item.name, item.note));
      if (FAILING.has(item.state)) unresolved += 1;
    }
  }
  out.write(`${changed} change(s) ${options.mode === 'write' ? 'made' : 'would be made'}; ${unresolved} left unresolved.\n`);
  // A write that leaves a collision or an unstubbable source behind has not
  // finished the job, so a chained command notices.
  return options.mode === 'write' && unresolved > 0 ? 1 : 0;
}

// Compared as real file paths so the guard also holds when the skills folder is
// reached through a link, as it is for Claude Code.
const invokedDirectly = Boolean(process.argv[1]) && existsSync(process.argv[1])
  && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
if (invokedDirectly) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`claude-skill-stubs: ${error.message}\n`);
    process.exitCode = 2;
  }
}
