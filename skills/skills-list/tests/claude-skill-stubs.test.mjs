import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import {
  existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync,
  symlinkSync, unlinkSync, utimesSync, writeFileSync,
} from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Every fixture is a throwaway repository under the OS temp folder. Nothing here
// reads or writes ~/.codex, ~/.claude or a real repository.
const script = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'scripts', 'claude-skill-stubs.mjs');
const MARKER = '<!-- generated by claude-skill-stubs; do not edit -->';

const sandboxes = [];
function repo() {
  const dir = mkdtempSync(path.join(os.tmpdir(), 'claude-stubs-'));
  sandboxes.push(dir);
  return dir;
}
test.after(() => {
  for (const dir of sandboxes) rmSync(dir, { recursive: true, force: true });
});

function writeSource(root, name, text) {
  const dir = path.join(root, '.codex', 'skills', name);
  mkdirSync(dir, { recursive: true });
  writeFileSync(path.join(dir, 'SKILL.md'), text);
}

function sourceText(name, { description = `The ${name} skill for fixture repositories.`, eol = '\n', metadata = false } = {}) {
  const lines = ['---', `name: ${name}`, `description: ${description}`];
  if (metadata) lines.push('metadata:', '  group: build');
  lines.push('---', '', `# ${name}`, '', 'Follow the method in references/method.md.', '');
  return lines.join(eol);
}

const stubPath = (root, name) => path.join(root, '.claude', 'skills', name, 'SKILL.md');
const frontmatter = (text) => text.match(/^﻿?---\r?\n[\s\S]*?\r?\n---(?:\r?\n|$)/)?.[0];

function run(root, ...args) {
  const result = spawnSync(process.execPath, [script, '--root', root, ...args], { encoding: 'utf8', timeout: 60000 });
  assert.equal(result.error, undefined, 'the script finishes');
  return { status: result.status, out: result.stdout + result.stderr };
}

test('write creates a stub per source skill with the source frontmatter verbatim', () => {
  const root = repo();
  writeSource(root, 'alpha', sourceText('alpha', { metadata: true }));
  writeSource(root, 'beta', sourceText('beta', { description: '"Quoted: a description with a colon."' }));

  const preview = run(root);
  assert.equal(preview.status, 0, preview.out);
  assert.match(preview.out, /create\s+alpha/);
  assert.equal(existsSync(stubPath(root, 'alpha')), false, 'the default mode writes nothing');

  const write = run(root, '--write');
  assert.equal(write.status, 0, write.out);
  for (const name of ['alpha', 'beta']) {
    const source = readFileSync(path.join(root, '.codex', 'skills', name, 'SKILL.md'), 'utf8');
    const stub = readFileSync(stubPath(root, name), 'utf8');
    assert.equal(frontmatter(stub), frontmatter(source), `${name}: frontmatter is byte-identical`);
    assert.ok(stub.includes(MARKER), `${name}: marker`);
    assert.ok(stub.includes(`Read and follow \`.codex/skills/${name}/SKILL.md\``), `${name}: pointer sentence`);
    assert.match(stub, /references and scripts resolve from that folder/, `${name}: resolution note`);
    assert.match(stub, /claude-skill-stubs\.mjs --write/, `${name}: regenerate command`);
    assert.doesNotMatch(stub, new RegExp(String.fromCharCode(0x2014)), `${name}: no em dash`);
  }

  const check = run(root, '--check');
  assert.equal(check.status, 0, check.out);
});

test('a source edit makes check fail and write repair it', () => {
  const root = repo();
  writeSource(root, 'alpha', sourceText('alpha'));
  writeSource(root, 'beta', sourceText('beta'));
  assert.equal(run(root, '--write').status, 0);

  writeSource(root, 'alpha', sourceText('alpha', { description: 'A changed trigger description.' }));
  const stale = run(root, '--check');
  assert.equal(stale.status, 1, stale.out);
  assert.match(stale.out, /stale\s+alpha/);
  assert.doesNotMatch(stale.out, /stale\s+beta/);

  const write = run(root, '--write');
  assert.equal(write.status, 0, write.out);
  assert.match(write.out, /update\s+alpha/);
  assert.match(readFileSync(stubPath(root, 'alpha'), 'utf8'), /description: A changed trigger description\./);
  assert.equal(run(root, '--check').status, 0);
});

test('a missing stub fails check', () => {
  const root = repo();
  writeSource(root, 'alpha', sourceText('alpha'));
  const check = run(root, '--check');
  assert.equal(check.status, 1, check.out);
  assert.match(check.out, /missing\s+alpha/);
});

test('a deleted source leaves an orphan that write removes', () => {
  const root = repo();
  writeSource(root, 'alpha', sourceText('alpha'));
  writeSource(root, 'beta', sourceText('beta'));
  assert.equal(run(root, '--write').status, 0);

  rmSync(path.join(root, '.codex', 'skills', 'beta'), { recursive: true, force: true });
  const orphan = run(root, '--check');
  assert.equal(orphan.status, 1, orphan.out);
  assert.match(orphan.out, /orphan\s+beta/);

  const write = run(root, '--write');
  assert.equal(write.status, 0, write.out);
  assert.match(write.out, /remove\s+beta/);
  assert.equal(existsSync(path.join(root, '.claude', 'skills', 'beta')), false, 'the orphaned stub folder is gone');
  assert.ok(existsSync(stubPath(root, 'alpha')), 'the live stub stays');
  assert.equal(run(root, '--check').status, 0);
});

test('a hand-written claude skill without the marker is left alone', () => {
  const root = repo();
  writeSource(root, 'alpha', sourceText('alpha'));
  const own = stubPath(root, 'own');
  mkdirSync(path.dirname(own), { recursive: true });
  const ownText = '---\nname: own\ndescription: A Claude-only skill this repository wrote by hand.\n---\n\nBody.\n';
  writeFileSync(own, ownText);

  const write = run(root, '--write');
  assert.equal(write.status, 0, write.out);
  assert.equal(readFileSync(own, 'utf8'), ownText, 'the own skill is untouched');

  const check = run(root, '--check');
  assert.equal(check.status, 0, check.out);
  assert.match(check.out, /own\s+own: own skill, left alone/);
});

test('a CRLF source yields a CRLF stub and an LF source an LF stub', () => {
  const root = repo();
  writeSource(root, 'windows', sourceText('windows', { eol: '\r\n' }));
  writeSource(root, 'unix', sourceText('unix'));
  assert.equal(run(root, '--write').status, 0);

  const crlf = readFileSync(stubPath(root, 'windows'), 'utf8');
  assert.ok(crlf.includes('\r\n'), 'the stub has CRLF line endings');
  assert.doesNotMatch(crlf, /[^\r]\n/, 'no bare LF in a CRLF stub');
  assert.doesNotMatch(readFileSync(stubPath(root, 'unix'), 'utf8'), /\r/, 'no CR in an LF stub');
  assert.equal(run(root, '--check').status, 0);
});

test('a name collision with an own skill fails check and write skips it', () => {
  const root = repo();
  writeSource(root, 'shared', sourceText('shared'));
  const own = stubPath(root, 'shared');
  mkdirSync(path.dirname(own), { recursive: true });
  const ownText = '---\nname: shared\ndescription: A hand-written Claude skill with a clashing name.\n---\n\nBody.\n';
  writeFileSync(own, ownText);

  const check = run(root, '--check');
  assert.equal(check.status, 1, check.out);
  assert.match(check.out, /collision\s+shared/);

  const write = run(root, '--write');
  assert.equal(write.status, 1, write.out);
  assert.match(write.out, /collision\s+shared/);
  assert.equal(readFileSync(own, 'utf8'), ownText, 'the colliding own skill is untouched');
});

test('a source without frontmatter or name is reported and skipped', () => {
  const root = repo();
  writeSource(root, 'bare', '# No frontmatter here\n');
  writeSource(root, 'nameless', '---\ndescription: Has no name.\n---\n\nBody.\n');
  writeSource(root, 'good', sourceText('good'));

  const write = run(root, '--write');
  assert.equal(write.status, 1, write.out);
  assert.match(write.out, /invalid\s+bare: no frontmatter/);
  assert.match(write.out, /invalid\s+nameless: no name/);
  assert.equal(existsSync(stubPath(root, 'bare')), false);
  assert.equal(existsSync(stubPath(root, 'nameless')), false);
  assert.ok(existsSync(stubPath(root, 'good')), 'valid sources are still stubbed');

  assert.equal(run(root, '--check').status, 1, 'an unstubbable source is a check failure');
});

test('write leaves a matching stub unwritten', () => {
  const root = repo();
  writeSource(root, 'alpha', sourceText('alpha'));
  assert.equal(run(root, '--write').status, 0);
  const past = new Date('2020-01-01T00:00:00Z');
  utimesSync(stubPath(root, 'alpha'), past, past);

  const write = run(root, '--write');
  assert.equal(write.status, 0, write.out);
  assert.doesNotMatch(write.out, /update\s+alpha/);
  assert.equal(statSync(stubPath(root, 'alpha')).mtimeMs, past.getTime(), 'identical bytes are not rewritten');
});

// A linked .claude/skills would make every stub write land on a source file.
test('a linked claude skills folder is refused before anything is written', (t) => {
  const root = repo();
  writeSource(root, 'alpha', sourceText('alpha'));
  const link = path.join(root, '.claude', 'skills');
  mkdirSync(path.dirname(link), { recursive: true });
  symlinkSync(path.join(root, '.codex', 'skills'), link, process.platform === 'win32' ? 'junction' : 'dir');
  t.after(() => {
    if (lstatSync(link, { throwIfNoEntry: false })?.isSymbolicLink()) unlinkSync(link);
  });
  const before = readFileSync(path.join(root, '.codex', 'skills', 'alpha', 'SKILL.md'), 'utf8');

  const write = run(root, '--write');
  assert.equal(write.status, 2, write.out);
  assert.match(write.out, /link/);
  assert.equal(readFileSync(path.join(root, '.codex', 'skills', 'alpha', 'SKILL.md'), 'utf8'), before, 'the source is untouched');
});
